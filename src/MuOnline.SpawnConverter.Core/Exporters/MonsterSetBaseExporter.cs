namespace MuOnline.SpawnConverter.Core.Exporters;

using System.Text;
using MuOnline.SpawnConverter.Core.Data;
using MuOnline.SpawnConverter.Core.Models;

/// <summary>
/// Exports spawn areas back into a standard, cleanly formatted MonsterSetBase.txt file.
/// </summary>
public sealed class MonsterSetBaseExporter : ISpawnExporter
{
    public string FormatName => "msb";

    public string Export(IEnumerable<SpawnArea> spawns)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// ===========================================================================");
        sb.AppendLine("// MonsterSetBase.txt generated by muonline-spawn-converter");
        sb.AppendLine("// GitHub: https://github.com/hellonullen/muonline-spawn-converter");
        sb.AppendLine("// ===========================================================================");
        sb.AppendLine();

        var spawnList = spawns.ToList();

        // ---------------- Section 0: Static NPCs & Single Spawns ----------------
        var staticSpawns = spawnList.Where(s => s.IsPoint && s.Quantity == 1).ToList();
        sb.AppendLine("// ---------------------------------------------------------------------------");
        sb.AppendLine("// Section 0: Static NPCs and Monsters");
        sb.AppendLine("// Format: MobID  MapID  Distance  X  Y  Dir  // Name");
        sb.AppendLine("// ---------------------------------------------------------------------------");
        sb.AppendLine("0");
        foreach (var s in staticSpawns)
        {
            int webzenDir = DirectionHelper.ToWebzenDirection(s.Direction);
            string mobName = StandardMonsters.GetMonsterName(s.MonsterNumber);
            string mapName = StandardGameMaps.GetMapName(s.MapNumber);
            string comment = !string.IsNullOrEmpty(s.Comment) ? s.Comment : $"{mobName} ({mapName})";

            sb.AppendLine($"\t{s.MonsterNumber,-5}\t{s.MapNumber,-4}\t{s.Distance,-4}\t{s.X1,-4}\t{s.Y1,-4}\t{webzenDir,-3}\t// {comment}");
        }
        sb.AppendLine("end");
        sb.AppendLine();

        // ---------------- Section 1: Area Spawns ----------------
        var areaSpawns = spawnList.Where(s => !s.IsPoint).ToList();
        sb.AppendLine("// ---------------------------------------------------------------------------");
        sb.AppendLine("// Section 1: Area Roaming Monsters");
        sb.AppendLine("// Format: MobID  MapID  Distance  X1  Y1  X2  Y2  Dir  Quantity  // Name");
        sb.AppendLine("// ---------------------------------------------------------------------------");
        sb.AppendLine("1");
        foreach (var s in areaSpawns)
        {
            int webzenDir = DirectionHelper.ToWebzenDirection(s.Direction);
            string mobName = StandardMonsters.GetMonsterName(s.MonsterNumber);
            string mapName = StandardGameMaps.GetMapName(s.MapNumber);
            string comment = !string.IsNullOrEmpty(s.Comment) ? s.Comment : $"{mobName} ({mapName})";

            sb.AppendLine($"\t{s.MonsterNumber,-5}\t{s.MapNumber,-4}\t{s.Distance,-4}\t{s.X1,-4}\t{s.Y1,-4}\t{s.X2,-4}\t{s.Y2,-4}\t{webzenDir,-3}\t{s.Quantity,-4}\t// {comment}");
        }
        sb.AppendLine("end");
        sb.AppendLine();

        // ---------------- Section 2: Point Spots ----------------
        var pointSpots = spawnList.Where(s => s.IsPoint && s.Quantity > 1).ToList();
        if (pointSpots.Count > 0)
        {
            sb.AppendLine("// ---------------------------------------------------------------------------");
            sb.AppendLine("// Section 2: Point Spots (Multiple monsters at same coordinate)");
            sb.AppendLine("// Format: MobID  MapID  Distance  X  Y  Dir  Quantity  // Name");
            sb.AppendLine("// ---------------------------------------------------------------------------");
            sb.AppendLine("2");
            foreach (var s in pointSpots)
            {
                int webzenDir = DirectionHelper.ToWebzenDirection(s.Direction);
                string mobName = StandardMonsters.GetMonsterName(s.MonsterNumber);
                string mapName = StandardGameMaps.GetMapName(s.MapNumber);
                string comment = !string.IsNullOrEmpty(s.Comment) ? s.Comment : $"{mobName} Spot ({mapName})";

                sb.AppendLine($"\t{s.MonsterNumber,-5}\t{s.MapNumber,-4}\t{s.Distance,-4}\t{s.X1,-4}\t{s.Y1,-4}\t{webzenDir,-3}\t{s.Quantity,-4}\t// {comment}");
            }
            sb.AppendLine("end");
            sb.AppendLine();
        }

        return sb.ToString();
    }
}
